-- ============================================================
-- MediFlow: safe migration from single-clinic to multi-tenant
-- ------------------------------------------------------------
-- Run once as the application schema owner (the same user that
-- owns the existing patients/doctors/appointments/users tables):
--
--   sqlplus clinic/ChangeMe_123@localhost:1521/FREEPDB1
--   SQL> @sql/06_multi_tenant_migration.sql
--
-- This script is IDEMPOTENT and NON-DESTRUCTIVE:
--   * no table is dropped or recreated
--   * no patient, doctor, appointment or user row is deleted
--   * existing accounts keep their usernames, hashes and roles
--   * all existing clinical records are assigned to one default
--     clinic so nothing disappears from the existing UI
--
-- New:
--   * CLINICS table (one row per tenant)
--   * clinic_id on USERS, PATIENTS, DOCTORS, APPOINTMENTS
--   * composite FKs that make a patient/doctor/appointment pair
--     impossible across two different clinics
--   * per-clinic phone uniqueness (two clinics may reuse a phone)
--   * CLINIC_ADMIN / PLATFORM_ADMIN roles
-- ============================================================
SET DEFINE OFF
WHENEVER SQLERROR EXIT FAILURE

PROMPT Creating CLINICS table ...
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE clinics (
      clinic_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      clinic_name   VARCHAR2(150) NOT NULL,
      slug          VARCHAR2(80)  NOT NULL UNIQUE,
      email         VARCHAR2(100),
      status        VARCHAR2(20)  DEFAULT ''ACTIVE'' NOT NULL,
      is_default    NUMBER(1)     DEFAULT 0 NOT NULL,
      created_at    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
      CONSTRAINT chk_clinic_status CHECK (status IN (''ACTIVE'',''SUSPENDED'')),
      CONSTRAINT chk_clinic_default CHECK (is_default IN (0,1))
    )';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN  -- ORA-00955: name already used
      RAISE;
    END IF;
END;
/

PROMPT Creating/refreshing the default clinic for existing records ...
DECLARE
  v_count NUMBER;
  v_id    NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM clinics WHERE slug = 'default-clinic';
  IF v_count = 0 THEN
    INSERT INTO clinics (clinic_name, slug, email, status, is_default)
    VALUES ('MediFlow Clinic', 'default-clinic', NULL, 'ACTIVE', 1);
  END IF;

  SELECT clinic_id INTO v_id FROM clinics WHERE slug = 'default-clinic';
  UPDATE clinics SET is_default = 0 WHERE clinic_id <> v_id;
  UPDATE clinics SET is_default = 1, status = 'ACTIVE' WHERE clinic_id = v_id;
  COMMIT;
END;
/

-- Only one tenant may be marked as the legacy/default tenant.
BEGIN
  EXECUTE IMMEDIATE
    'CREATE UNIQUE INDEX uq_clinics_default ON clinics (CASE WHEN is_default = 1 THEN 1 END)';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE NOT IN (-1408, -955) THEN  -- index/name already exists
      RAISE;
    END IF;
END;
/

PROMPT Adding clinic_id columns ...
BEGIN
