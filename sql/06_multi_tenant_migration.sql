PROMPT Updating roles and user scope rules ...
BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE users DROP CONSTRAINT chk_user_role';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -2443 THEN RAISE; END IF;  -- ORA-02443
END;
/
BEGIN
  EXECUTE IMMEDIATE
    'ALTER TABLE users ADD CONSTRAINT chk_user_role CHECK (role IN ('
    || '''ADMIN'', ''PLATFORM_ADMIN'', ''CLINIC_ADMIN'', ''RECEPTIONIST'', ''DOCTOR''))';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-2264, -2261, -2275) THEN RAISE; END IF;
END;
/
BEGIN
  EXECUTE IMMEDIATE
    'ALTER TABLE users ADD CONSTRAINT chk_users_clinic_scope CHECK ('
    || '(role IN (''ADMIN'', ''PLATFORM_ADMIN'') AND clinic_id IS NULL) OR '
    || '(role NOT IN (''ADMIN'', ''PLATFORM_ADMIN'') AND clinic_id IS NOT NULL))';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-2264, -2261, -2275) THEN RAISE; END IF;
END;
/

COMMIT;
PROMPT Migration complete. Verification:
COLUMN clinic_name FORMAT A30
SELECT clinic_id, clinic_name, slug, status, is_default FROM clinics ORDER BY clinic_id;
SELECT 'patients' AS table_name, COUNT(*) AS row_count,
       COUNT(DISTINCT clinic_id) AS clinics FROM patients
UNION ALL SELECT 'doctors', COUNT(*), COUNT(DISTINCT clinic_id) FROM doctors
UNION ALL SELECT 'appointments', COUNT(*), COUNT(DISTINCT clinic_id) FROM appointments
UNION ALL SELECT 'users', COUNT(*), COUNT(DISTINCT clinic_id) FROM users;
SELECT user_id, username, role, clinic_id FROM users ORDER BY user_id;
