PROMPT Assigning existing records to the default clinic ...
DECLARE
  v_default NUMBER;
BEGIN
  SELECT clinic_id INTO v_default FROM clinics WHERE slug = 'default-clinic';

  UPDATE patients     SET clinic_id = v_default WHERE clinic_id IS NULL;
  UPDATE doctors      SET clinic_id = v_default WHERE clinic_id IS NULL;
  UPDATE appointments SET clinic_id = v_default WHERE clinic_id IS NULL;

  -- Platform administrators are global: they have no tenant context.
  UPDATE users SET clinic_id = NULL
   WHERE role IN ('ADMIN', 'PLATFORM_ADMIN');
  -- Every other account belongs to the default clinic until reassigned.
  UPDATE users SET clinic_id = v_default
   WHERE clinic_id IS NULL
     AND role NOT IN ('ADMIN', 'PLATFORM_ADMIN');
  COMMIT;
END;
/

PROMPT Making clinical records tenant-mandatory ...
DECLARE
  v_nullable VARCHAR2(1);
BEGIN
  SELECT nullable INTO v_nullable FROM user_tab_columns
   WHERE table_name = 'PATIENTS' AND column_name = 'CLINIC_ID';
  IF v_nullable = 'Y' THEN
    EXECUTE IMMEDIATE 'ALTER TABLE patients MODIFY (clinic_id NOT NULL)';
  END IF;

  SELECT nullable INTO v_nullable FROM user_tab_columns
   WHERE table_name = 'DOCTORS' AND column_name = 'CLINIC_ID';
  IF v_nullable = 'Y' THEN
    EXECUTE IMMEDIATE 'ALTER TABLE doctors MODIFY (clinic_id NOT NULL)';
  END IF;

  SELECT nullable INTO v_nullable FROM user_tab_columns
   WHERE table_name = 'APPOINTMENTS' AND column_name = 'CLINIC_ID';
  IF v_nullable = 'Y' THEN
    EXECUTE IMMEDIATE 'ALTER TABLE appointments MODIFY (clinic_id NOT NULL)';
  END IF;
END;
/

PROMPT Replacing global phone uniqueness with per-clinic uniqueness ...
DECLARE
  v_name VARCHAR2(128);
BEGIN
  SELECT MIN(c.constraint_name) INTO v_name
    FROM user_constraints c
   WHERE c.table_name = 'PATIENTS'
     AND c.constraint_type = 'U'
     AND EXISTS (
       SELECT 1 FROM user_cons_columns cc
        WHERE cc.constraint_name = c.constraint_name
          AND cc.column_name = 'PHONE');
  IF v_name IS NOT NULL THEN
    EXECUTE IMMEDIATE 'ALTER TABLE patients DROP CONSTRAINT ' || v_name;
  END IF;
END;
/
DECLARE
  v_name VARCHAR2(128);
BEGIN
  SELECT MIN(c.constraint_name) INTO v_name
    FROM user_constraints c
   WHERE c.table_name = 'DOCTORS'
     AND c.constraint_type = 'U'
     AND EXISTS (
       SELECT 1 FROM user_cons_columns cc
        WHERE cc.constraint_name = c.constraint_name
          AND cc.column_name = 'PHONE');
  IF v_name IS NOT NULL THEN
    EXECUTE IMMEDIATE 'ALTER TABLE doctors DROP CONSTRAINT ' || v_name;
  END IF;
END;
/
BEGIN
  EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX uq_patients_clinic_phone ON patients (clinic_id, phone)';
