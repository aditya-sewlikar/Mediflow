PROMPT Adding tenant-qualified keys and foreign keys ...
-- Direct ownership FKs: every tenant key must resolve to a real clinic even on
-- a database that was converted from the original single-clinic schema.
BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE patients ADD CONSTRAINT fk_patient_clinic '
    || 'FOREIGN KEY (clinic_id) REFERENCES clinics (clinic_id)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-2264, -2261, -2275) THEN RAISE; END IF;
END;
/
BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE doctors ADD CONSTRAINT fk_doctor_clinic '
    || 'FOREIGN KEY (clinic_id) REFERENCES clinics (clinic_id)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-2264, -2261, -2275) THEN RAISE; END IF;
END;
/
BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE appointments ADD CONSTRAINT fk_appt_clinic '
    || 'FOREIGN KEY (clinic_id) REFERENCES clinics (clinic_id)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-2264, -2261, -2275) THEN RAISE; END IF;
END;
/
-- Unique (id, clinic_id) keys are required by the composite appointment FKs.
BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE patients ADD CONSTRAINT uq_patient_tenant_id UNIQUE (patient_id, clinic_id)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-2264, -2261, -2275) THEN RAISE; END IF;
END;
/
BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE doctors ADD CONSTRAINT uq_doctor_tenant_id UNIQUE (doctor_id, clinic_id)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-2264, -2261, -2275) THEN RAISE; END IF;
END;
/
BEGIN
  EXECUTE IMMEDIATE
    'ALTER TABLE appointments ADD CONSTRAINT fk_appt_patient_tenant '
    || 'FOREIGN KEY (patient_id, clinic_id) REFERENCES patients (patient_id, clinic_id)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-2264, -2261, -2275) THEN RAISE; END IF;
END;
/
BEGIN
  EXECUTE IMMEDIATE
    'ALTER TABLE appointments ADD CONSTRAINT fk_appt_doctor_tenant '
    || 'FOREIGN KEY (doctor_id, clinic_id) REFERENCES doctors (doctor_id, clinic_id)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-2264, -2261, -2275) THEN RAISE; END IF;
END;
/
BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE users ADD CONSTRAINT fk_users_clinic '
    || 'FOREIGN KEY (clinic_id) REFERENCES clinics (clinic_id)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-2264, -2261, -2275) THEN RAISE; END IF;
END;
/

