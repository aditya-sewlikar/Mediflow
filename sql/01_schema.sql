-- TENANT / CLINIC TABLE
CREATE TABLE clinics (
  clinic_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_name   VARCHAR2(150) NOT NULL,
  slug          VARCHAR2(80)  NOT NULL UNIQUE,
  email         VARCHAR2(100),
  status        VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL,
  is_default    NUMBER(1)     DEFAULT 0 NOT NULL,
  created_at    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT chk_clinic_status CHECK (status IN ('ACTIVE','SUSPENDED')),
  CONSTRAINT chk_clinic_default CHECK (is_default IN (0,1))
);

-- Exactly one legacy/default tenant (function-based unique index: NULLs are
-- allowed, so many non-default clinics can coexist).
CREATE UNIQUE INDEX uq_clinics_default ON clinics (CASE WHEN is_default = 1 THEN 1 END);

-- The default clinic owns records created before the multi-tenant migration.
INSERT INTO clinics (clinic_name, slug, email, status, is_default)
VALUES ('MediFlow Clinic', 'default-clinic', NULL, 'ACTIVE', 1);

-- PATIENT TABLE (one directory per clinic)
CREATE TABLE patients (
  patient_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id      NUMBER NOT NULL,
  full_name      VARCHAR2(100) NOT NULL,
  phone          VARCHAR2(15)  NOT NULL,
  email          VARCHAR2(100),
  gender         VARCHAR2(10),
  date_of_birth  DATE,
  created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_patient_clinic FOREIGN KEY (clinic_id)
      REFERENCES clinics(clinic_id),
  CONSTRAINT uq_patient_tenant_id UNIQUE (patient_id, clinic_id)
);

-- Phone numbers are unique inside a clinic, not across the whole platform.
CREATE UNIQUE INDEX uq_patients_clinic_phone ON patients (clinic_id, phone);
CREATE INDEX idx_patients_clinic ON patients (clinic_id);

-- DOCTOR TABLE (one roster per clinic)
CREATE TABLE doctors (
  doctor_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id       NUMBER NOT NULL,
  full_name       VARCHAR2(100) NOT NULL,
  specialization  VARCHAR2(80)  NOT NULL,
  phone           VARCHAR2(15),
  availability    VARCHAR2(20)  DEFAULT 'AVAILABLE' NOT NULL,
  CONSTRAINT chk_doctor_availability CHECK
      (availability IN ('AVAILABLE','BUSY','OFFLINE')),
  CONSTRAINT fk_doctor_clinic FOREIGN KEY (clinic_id)
      REFERENCES clinics(clinic_id),
  CONSTRAINT uq_doctor_tenant_id UNIQUE (doctor_id, clinic_id)
);

-- Phone is optional, so the unique key falls back to a per-doctor marker for
-- blank phones. Otherwise Oracle treats two NULL phones in one clinic as a
-- duplicate and the second doctor cannot be added.
CREATE UNIQUE INDEX uq_doctors_clinic_phone
    ON doctors (clinic_id, NVL(phone, 'NO-PHONE-' || TO_CHAR(doctor_id)));
CREATE INDEX idx_doctors_clinic ON doctors (clinic_id);

-- APPOINTMENT AND QUEUE TABLE
-- The composite FKs are the database-level isolation guarantee: an appointment
-- can only reference a patient AND a doctor that belong to its own clinic.
CREATE TABLE appointments (
  appointment_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id             NUMBER NOT NULL,
  patient_id            NUMBER NOT NULL,
  doctor_id             NUMBER NOT NULL,
  appointment_datetime  TIMESTAMP NOT NULL,
  token_no              NUMBER,
  status                VARCHAR2(20) DEFAULT 'BOOKED' NOT NULL,
  reason                VARCHAR2(250),
  CONSTRAINT fk_appt_clinic FOREIGN KEY (clinic_id)
      REFERENCES clinics(clinic_id),
  CONSTRAINT fk_appt_patient FOREIGN KEY (patient_id)
      REFERENCES patients(patient_id),
  CONSTRAINT fk_appt_doctor FOREIGN KEY (doctor_id)
      REFERENCES doctors(doctor_id),
  CONSTRAINT fk_appt_patient_tenant FOREIGN KEY (patient_id, clinic_id)
      REFERENCES patients(patient_id, clinic_id),
  CONSTRAINT fk_appt_doctor_tenant FOREIGN KEY (doctor_id, clinic_id)
      REFERENCES doctors(doctor_id, clinic_id),
  CONSTRAINT chk_appt_status CHECK
      (status IN ('BOOKED','WAITING','IN_PROGRESS','COMPLETED','CANCELLED')),
  CONSTRAINT uq_doctor_token UNIQUE
      (doctor_id, appointment_datetime, token_no)
);

CREATE INDEX idx_appt_doctor_time ON appointments (doctor_id, appointment_datetime);
CREATE INDEX idx_appt_patient     ON appointments (patient_id);
CREATE INDEX idx_appt_clinic      ON appointments (clinic_id, appointment_datetime);

-- USERS (platform admins are global; every other account has exactly one clinic)
CREATE TABLE users (
  user_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id      NUMBER,
  full_name      VARCHAR2(100) NOT NULL,
  username       VARCHAR2(50)  NOT NULL UNIQUE,
  email          VARCHAR2(100),
  password_hash  VARCHAR2(255) NOT NULL,
  role           VARCHAR2(20)  DEFAULT 'RECEPTIONIST' NOT NULL,
  CONSTRAINT chk_user_role CHECK (role IN
      ('ADMIN','PLATFORM_ADMIN','CLINIC_ADMIN','RECEPTIONIST','DOCTOR')),
  CONSTRAINT fk_users_clinic FOREIGN KEY (clinic_id)
      REFERENCES clinics(clinic_id),
  CONSTRAINT chk_users_clinic_scope CHECK (
      (role IN ('ADMIN','PLATFORM_ADMIN') AND clinic_id IS NULL) OR
      (role NOT IN ('ADMIN','PLATFORM_ADMIN') AND clinic_id IS NOT NULL))
);

CREATE UNIQUE INDEX uq_users_username_ci ON users (UPPER(username));
CREATE UNIQUE INDEX uq_users_email_ci    ON users (LOWER(email));
CREATE INDEX idx_users_clinic ON users (clinic_id);

COMMIT;
